const MONTHLY_REQUESTS = Array.from({ length: 60 }, (_, index) => {
  const year = 2020 + Math.floor(index / 12);
  const month = index % 12;

  return Array.from({ length: 5 }, (_, requestIndex) => {
    const requestNumber = index * 5 + requestIndex;
    const date = new Date(year, month, [3, 8, 14, 20, 26][requestIndex]);

    return {
      id: 1201 + requestNumber * 13,
      employeeId: EMPLOYEE_IDS[requestNumber % EMPLOYEE_IDS.length],
      amount: 1800 + ((requestNumber * 791) % 4201),
      date,
      payrollDate: new Date(year, month + 1, 15),
      status: year < 2023
        ? [PaymentStatus.COMPLETED, PaymentStatus.ERROR, PaymentStatus.COMPLETED][requestNumber % 3]
        : [PaymentStatus.COMPLETED, PaymentStatus.PENDING, PaymentStatus.ERROR][requestNumber % 3],
    };
  });
}).flat();

export const PAYMENTS: Payment[] = [...BASE_PAYMENTS, ...MONTHLY_REQUESTS];
